-- Profiles: Public read, User edit own
CREATE POLICY "Public profiles are viewable by everyone" ON profiles FOR SELECT USING (true);
CREATE POLICY "Users can insert their own profile" ON profiles FOR INSERT WITH CHECK (auth.uid() = id);
CREATE POLICY "Users can update own profile" ON profiles FOR UPDATE USING (auth.uid() = id);

-- Attendance: partial policy (Admins all, Students view own)
CREATE POLICY "Admins view all attendance" ON attendance FOR ALL USING (
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role IN ('admin', 'teacher'))
);
CREATE POLICY "Students view own attendance" ON attendance FOR SELECT USING (student_id = auth.uid());

-- Fees: Admins all, Students view own
CREATE POLICY "Admins view all fees" ON fee_payments FOR ALL USING (
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role IN ('admin', 'teacher'))
);
CREATE POLICY "Students view own fees" ON fee_payments FOR SELECT USING (student_id = auth.uid());


-- Function to check if the current user has overdue fees
CREATE OR REPLACE FUNCTION public.has_overdue_fees()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1
    FROM public.fee_payments
    WHERE student_id = auth.uid() -- Matches the currently logged-in user
    AND status = 'overdue'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Resources: Logic-based access (No Pay, No Notes)
CREATE POLICY "Enforce Premium Content Access" ON resources FOR SELECT USING (
  -- Condition 1: Everyone can see 'free' content
  access_level = 'free'
  OR
  -- Condition 2: To see 'premium', you must NOT have overdue fees
  (
    access_level = 'premium' 
    AND 
    NOT public.has_overdue_fees()
  )
);
